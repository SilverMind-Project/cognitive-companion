"""Export the composed FastAPI route-permission reference (`docs/api/permissions.md`).

Usage::

    uv run --project backend python backend/scripts/export_route_permissions.py
    uv run --project backend python backend/scripts/export_route_permissions.py --check

Walks ``backend.main.app`` through FastAPI's ``iter_route_contexts`` (the same
traversal used by OpenAPI generation and ``test_route_auth_coverage.py``) and
``config/auth.yaml`` ``roles:``, rendering the deterministic permissions reference.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from fastapi.routing import APIRoute, iter_route_contexts
from starlette.routing import WebSocketRoute

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from backend.core.auth import (  # noqa: E402
    ALLOWED_ACTIONS,
    WS_ROUTE_TOKENS,
    AuthContext,
    KeyStore,
    is_valid_d4_token,
)

AUTH_YAML_PATH = REPO_ROOT / "config" / "auth.yaml"
DEFAULT_OUTPUT_PATH = REPO_ROOT / "docs" / "api" / "permissions.md"


@dataclass(frozen=True)
class RoutePermissionRow:
    method: str
    path: str
    declared_token: str
    auth_kind: str
    reaching_roles: tuple[str, ...]


def _auth_checkers(route: Any) -> list[Any]:
    found: list[Any] = []
    stack = list(route.dependant.dependencies)
    while stack:
        dep = stack.pop()
        if getattr(dep.call, "__cc_auth_checker__", False):
            found.append(dep.call)
        stack.extend(dep.dependencies)
    return found


def _primary_method(methods: set[str] | None) -> str:
    return sorted((methods or set()) - {"HEAD", "OPTIONS"})[0]


def load_keystore(auth_yaml: Path = AUTH_YAML_PATH) -> KeyStore:
    """Load a :class:`KeyStore` from *auth_yaml*."""
    data = yaml.safe_load(auth_yaml.read_text(encoding="utf-8")) or {}
    return KeyStore(
        api_keys=data.get("api_keys", []),
        device_keys=data.get("device_keys", []),
        roles=data.get("roles", {}),
    )


def collect_route_inventory(auth_yaml: Path = AUTH_YAML_PATH) -> list[RoutePermissionRow]:
    """Walk the composed app and compute role reachability for every guarded route."""
    import backend.main

    ks = load_keystore(auth_yaml)
    role_order = list(ks.roles)
    rows: list[RoutePermissionRow] = []

    for ctx in iter_route_contexts(backend.main.app.routes):
        orig = ctx.original_route
        if isinstance(orig, APIRoute):
            checkers = _auth_checkers(ctx)
            if not checkers:
                continue
            declared_tokens = tuple(getattr(checkers[0], "__cc_auth_tokens__", ()))
            declared = declared_tokens[0] if declared_tokens else ""
            method = _primary_method(ctx.methods)
            route_path = ctx.path or ""
            reaching = tuple(
                role
                for role in role_order
                if ks.has_token(AuthContext(key="inventory", name=role, roles=[role]), declared)
            )
            rows.append(
                RoutePermissionRow(
                    method=method,
                    path=route_path,
                    declared_token=declared,
                    auth_kind="http",
                    reaching_roles=reaching,
                )
            )
        elif isinstance(orig, WebSocketRoute) and orig.path in WS_ROUTE_TOKENS:
            token = WS_ROUTE_TOKENS[orig.path]
            reaching = tuple(
                role
                for role in role_order
                if ks.has_token(AuthContext(key="inventory", name=role, roles=[role]), token)
            )
            rows.append(
                RoutePermissionRow(
                    method="WS",
                    path=orig.path,
                    declared_token=token,
                    auth_kind="ws",
                    reaching_roles=reaching,
                )
            )

    rows.sort(key=lambda r: (r.declared_token, r.path, r.method))
    return rows


def render_permissions_markdown(
    rows: list[RoutePermissionRow],
    ks: KeyStore,
) -> str:
    """Render deterministic markdown for ``docs/api/permissions.md``."""
    roles_map = ks.roles
    non_super_roles = [r for r, toks in roles_map.items() if "*" not in toks]
    http_rows = [r for r in rows if r.auth_kind == "http"]
    ws_rows = [r for r in rows if r.auth_kind == "ws"]
    distinct_tokens = sorted({r.declared_token for r in rows})
    actions_str = ", ".join(f"`{a}`" for a in sorted(ALLOWED_ACTIONS))

    lines: list[str] = [
        "# Permission Token Reference",
        "",
        "Generated by `backend/scripts/export_route_permissions.py` from the composed FastAPI",
        "application (`backend.main.app`) and `config/auth.yaml`. Do not hand-edit; re-run the",
        "exporter and commit the diff. Verified by `backend/tests/contracts/test_permissions_migration_drift.py`.",
        "",
        "## Model",
        "",
        "Every guarded HTTP route, authenticated WebSocket endpoint, and MCP tool declares exactly",
        "one D4 `<resource>:<action>` token. Roles are token sets defined exclusively under `roles:`",
        "in `config/auth.yaml`, and authorization checks pure token membership.",
        "",
        f"Closed D4 actions ({len(ALLOWED_ACTIONS)}): {actions_str}.",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Guarded HTTP routes | {len(http_rows)} |",
        f"| Authenticated WebSocket routes | {len(ws_rows)} |",
        f"| Distinct route and WebSocket D4 tokens | {len(distinct_tokens)} |",
        f"| Configured roles (`roles:`) | {len(roles_map)} |",
        "",
        "## Role Token Sets (`config/auth.yaml` `roles:`)",
        "",
        "| Role | Token count | Tokens |",
        "| --- | --- | --- |",
    ]
    for role, tokens in roles_map.items():
        tok_list = ", ".join(f"`{t}`" for t in tokens)
        lines.append(f"| `{role}` | {len(tokens)} | {tok_list} |")

    lines.extend(
        [
            "",
            "## Full Route and WebSocket Access Matrix",
            "",
            "Roles carrying `*` (`admin`, `operator`) reach every route below; the table shows",
            "reachability across the remaining configured roles.",
            "",
            "| D4 token | Method | Path | " + " | ".join(f"`{r}`" for r in non_super_roles) + " |",
            "| --- | --- | --- | " + " | ".join("---" for _ in non_super_roles) + " |",
        ]
    )
    for row in rows:
        if not is_valid_d4_token(row.declared_token):
            raise ValueError(
                f"Route {row.method} {row.path} declares non-D4 token {row.declared_token!r}"
            )
        cells = " | ".join("Y" if r in row.reaching_roles else "." for r in non_super_roles)
        lines.append(f"| `{row.declared_token}` | `{row.method}` | `{row.path}` | {cells} |")

    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_PATH,
        help="Destination markdown path (default: docs/api/permissions.md).",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if the generated markdown differs from --output.",
    )
    args = parser.parse_args(argv)

    ks = load_keystore()
    rows = collect_route_inventory()
    rendered = render_permissions_markdown(rows, ks)

    if args.check:
        if not args.output.exists():
            sys.stderr.write(f"Missing generated permissions doc: {args.output}\n")
            return 1
        existing = args.output.read_text(encoding="utf-8")
        if existing != rendered:
            sys.stderr.write(
                f"Permissions doc drift detected in {args.output}. "
                "Re-run backend/scripts/export_route_permissions.py.\n"
            )
            return 1
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
